import 'package:flutter/material.dart';

/// GenUI Component Types for WhizzMe AI
/// These are dynamic UI components generated based on AI context
enum GenUIComponentType {
  text, // Simple text response
  card, // Information card
  buttonGroup, // Action buttons
  form, // Input form
  list, // Ordered/unordered list
  quickReplies, // Quick reply chips
  statusCard, // Status indicator card
  stepList, // Step-by-step instructions
  linkCard, // External link card
  warningCard, // Warning/alert card
  successCard, // Success message card
  imageCard, // Image with caption
}

/// WhizzMe GenUI Component Model
/// Represents a dynamic UI component generated by AI
class WhizzMeGenUIComponent {
  final String id;
  final GenUIComponentType type;
  final Map<String, dynamic> data;
  final DateTime timestamp;
  final String? title;
  final String? subtitle;
  final List<GenUIAction>? actions;

  WhizzMeGenUIComponent({
    required this.id,
    required this.type,
    required this.data,
    DateTime? timestamp,
    this.title,
    this.subtitle,
    this.actions,
  }) : timestamp = timestamp ?? DateTime.now();

  /// Create from AI response
  factory WhizzMeGenUIComponent.fromAIResponse(
    String aiResponse,
    String category,
  ) {
    // Parse AI response and determine component type
    final parsedData = _parseAIResponse(aiResponse, category);

    return WhizzMeGenUIComponent(
      id: DateTime.now().millisecondsSinceEpoch.toString(),
      type: parsedData['type'] as GenUIComponentType,
      data: parsedData['data'] as Map<String, dynamic>,
      title: parsedData['title'] as String?,
      subtitle: parsedData['subtitle'] as String?,
      actions: parsedData['actions'] as List<GenUIAction>?,
    );
  }

  /// Parse AI response to extract structured data
  static Map<String, dynamic> _parseAIResponse(
    String response,
    String category,
  ) {
    // Default to text component
    GenUIComponentType type = GenUIComponentType.text;
    Map<String, dynamic> data = {'text': response};
    String? title;
    String? subtitle;
    List<GenUIAction>? actions;

    final lowerResponse = response.toLowerCase();

    // Detect component type based on content patterns
    if (lowerResponse.contains('step') ||
        lowerResponse.contains('first') ||
        lowerResponse.contains('then')) {
      type = GenUIComponentType.stepList;
      data = _extractSteps(response);
    } else if (lowerResponse.contains('try these') ||
        lowerResponse.contains('options') ||
        lowerResponse.contains('you can')) {
      type = GenUIComponentType.quickReplies;
      data = _extractQuickReplies(response, category);
      actions = _generateCategoryActions(category);
    } else if (lowerResponse.contains('warning') ||
        lowerResponse.contains('important') ||
        lowerResponse.contains('please note')) {
      type = GenUIComponentType.warningCard;
      data = {'text': response, 'icon': Icons.warning_amber_rounded};
    } else if (lowerResponse.contains('success') ||
        lowerResponse.contains('completed') ||
        lowerResponse.contains('done')) {
      type = GenUIComponentType.successCard;
      data = {'text': response, 'icon': Icons.check_circle_outline};
    } else if (lowerResponse.contains('password reset') ||
        lowerResponse.contains('verify') ||
        lowerResponse.contains('update')) {
      type = GenUIComponentType.card;
      data = {
        'text': response,
        'icon': _getCategoryIcon(category),
        'color': _getCategoryColor(category),
      };
      actions = _generateCategoryActions(category);
    }

    return {
      'type': type,
      'data': data,
      'title': title,
      'subtitle': subtitle,
      'actions': actions,
    };
  }

  /// Extract steps from response
  static Map<String, dynamic> _extractSteps(String response) {
    final steps = <String>[];
    final lines = response.split('\n');

    for (var line in lines) {
      final trimmed = line.trim();
      if (trimmed.isNotEmpty &&
          (trimmed.startsWith('1.') ||
              trimmed.startsWith('2.') ||
              trimmed.startsWith('3.') ||
              trimmed.startsWith('-') ||
              trimmed.toLowerCase().startsWith('first') ||
              trimmed.toLowerCase().startsWith('then') ||
              trimmed.toLowerCase().startsWith('next'))) {
        steps.add(trimmed);
      }
    }

    return {
      'steps': steps.isEmpty ? [response] : steps,
      'icon': Icons.format_list_numbered,
    };
  }

  /// Extract quick replies from response
  static Map<String, dynamic> _extractQuickReplies(
    String response,
    String category,
  ) {
    final replies = <String>[];

    // Category-specific quick replies
    switch (category) {
      case 'account_issues':
        replies.addAll([
          'Reset my password',
          'Verify my account',
          'Update profile',
          'Talk to agent',
        ]);
        break;
      case 'order_management':
        replies.addAll([
          'Check order status',
          'Cancel order',
          'Request refund',
          'Talk to agent',
        ]);
        break;
      case 'payment_issues':
        replies.addAll([
          'Check payout',
          'Payment failed',
          'Commission query',
          'Talk to agent',
        ]);
        break;
      case 'business_setup':
        replies.addAll([
          'Update menu',
          'Change hours',
          'Store settings',
          'Talk to agent',
        ]);
        break;
      case 'technical_support':
        replies.addAll([
          'App not working',
          'Report bug',
          'Feature request',
          'Talk to agent',
        ]);
        break;
      default:
        replies.addAll([
          'Tell me more',
          'I need help',
          'Talk to agent',
        ]);
    }

    return {
      'text': response,
      'replies': replies,
    };
  }

  /// Generate action buttons based on category
  static List<GenUIAction>? _generateCategoryActions(String category) {
    switch (category) {
      case 'account_issues':
        return [
          GenUIAction(
            label: 'Reset Password',
            action: 'reset_password',
            icon: Icons.lock_reset,
          ),
          GenUIAction(
            label: 'Contact Support',
            action: 'contact_support',
            icon: Icons.support_agent,
          ),
        ];
      case 'order_management':
        return [
          GenUIAction(
            label: 'View Orders',
            action: 'view_orders',
            icon: Icons.shopping_bag,
          ),
          GenUIAction(
            label: 'Contact Support',
            action: 'contact_support',
            icon: Icons.support_agent,
          ),
        ];
      case 'payment_issues':
        return [
          GenUIAction(
            label: 'View Payouts',
            action: 'view_payouts',
            icon: Icons.account_balance_wallet,
          ),
          GenUIAction(
            label: 'Contact Support',
            action: 'contact_support',
            icon: Icons.support_agent,
          ),
        ];
      default:
        return null;
    }
  }

  /// Get category icon
  static IconData _getCategoryIcon(String category) {
    switch (category) {
      case 'account_issues':
        return Icons.person_outline;
      case 'order_management':
        return Icons.shopping_bag_outlined;
      case 'payment_issues':
        return Icons.payment_outlined;
      case 'business_setup':
        return Icons.store_outlined;
      case 'technical_support':
        return Icons.bug_report_outlined;
      default:
        return Icons.help_outline;
    }
  }

  /// Get category color
  static Color _getCategoryColor(String category) {
    switch (category) {
      case 'account_issues':
        return Colors.orange;
      case 'order_management':
        return Colors.blue;
      case 'payment_issues':
        return Colors.green;
      case 'business_setup':
        return Colors.purple;
      case 'technical_support':
        return Colors.red;
      default:
        return Colors.grey;
    }
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'type': type.toString(),
        'data': data,
        'timestamp': timestamp.toIso8601String(),
        'title': title,
        'subtitle': subtitle,
        'actions': actions?.map((a) => a.toJson()).toList(),
      };
}

/// GenUI Action (button, link, etc.)
class GenUIAction {
  final String label;
  final String action;
  final IconData? icon;
  final Color? color;
  final bool isPrimary;

  GenUIAction({
    required this.label,
    required this.action,
    this.icon,
    this.color,
    this.isPrimary = false,
  });

  Map<String, dynamic> toJson() => {
        'label': label,
        'action': action,
        'isPrimary': isPrimary,
      };
}
